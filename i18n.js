  let language = "zh-CN";
  function normalize(value) { return value === "en" ? "en" : "zh-CN"; }
  function text(message, values = {}) {
    const translated = language === "zh-CN" && Object.hasOwn(zh, message) ? zh[message] : message;
    return String(translated).replace(/\{(\w+)\}/g, (token, key) =>
      Object.hasOwn(values, key) ? String(values[key]) : token);
  }
  function setLanguage(value) { language = normalize(value); }
  function apply(document) {
    document.documentElement.lang = language;
    for (const element of document.querySelectorAll("[data-i18n]"))
      element.textContent = text(element.getAttribute("data-i18n"));
    for (const attr of ["title", "aria-label", "placeholder"]) {
      for (const element of document.querySelectorAll(`[data-i18n-${attr}]`))
        element.setAttribute(attr, text(element.getAttribute(`data-i18n-${attr}`)));
    }
  }
  const api = { text, normalize, setLanguage, apply, messages: zh, get language() { return language; } };
